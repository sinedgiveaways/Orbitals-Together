"""Catalogue of the run's settings: every ORBITALS_* name the runtime reads, where, and the comment next to it.

Why: about 200 variables, read through cfg_get (runtime/core/base/cfg.h) or rt_knob all over runtime/, and some of the most
used (ORBITALS_FLIGHT_AT, ORBITALS_FLIGHT_SPIKE_MS) are in no README. Generated from the code each time, so it cannot go stale.

Usage: uv run tools/run/envs.py [REGEX]   e.g. envs.py FLIGHT, envs.py 'SEQ|CTL'
       uv run tools/run/envs.py --markdown > docs/environment-variables.md   the reference page, with each name's
       former name (tools/migrate/mkw-to-orbitals.tsv: the prefix rule and its exceptions)
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NAME = re.compile(r'"(ORBITALS_[A-Z0-9_]+)"')
KNOB = re.compile(r'rt_knob\("([A-Z0-9_]+)"')  # rt_knob prefixes ORBITALS_ itself (runtime/core/diag/perf.c)


def comment(lines: list[str], i: int) -> str:
    """The trailing // comment of line i, else the // block right above it."""
    if "//" in lines[i]:
        return lines[i].split("//", 1)[1].strip()
    above = []
    j = i - 1
    while j >= 0 and lines[j].strip().startswith("//") and len(above) < 4:
        above.insert(0, lines[j].strip()[2:].strip())
        j -= 1
    return " ".join(above)


def doc_mention(lines: list[str], name: str) -> str:
    """Where the file's comments describe name (often its header): from the name on, with the comment lines after."""
    for i, line in enumerate(lines):
        text = line.strip()
        if text.startswith("//") and re.search(rf"\b{name}\b", text):
            out = text[text.index(name) :]
            for nxt in lines[i + 1 : i + 4]:
                if not nxt.strip().startswith("//") or len(out) > 220:
                    break
                out += " " + nxt.strip()[2:].strip()
            return out
    return ""


def catalogue() -> dict[str, tuple[str, str]]:
    found: dict[str, tuple[str, str]] = {}
    for path in sorted((ROOT / "runtime").rglob("*")):
        if path.suffix not in {".c", ".cpp", ".h"}:
            continue
        lines = path.read_text(errors="replace").splitlines()
        for i, line in enumerate(lines):
            for name in NAME.findall(line) + [f"ORBITALS_{k}" for k in KNOB.findall(line)]:
                where = f"{path.relative_to(ROOT)}:{i + 1}"
                text = comment(lines, i) or doc_mention(lines, name)
                if name not in found or (text and not found[name][1]):
                    found[name] = (where, text)
    return found


MARKDOWN_HEAD = """# Environment variables

Every `ORBITALS_*` name the runtime reads, where, and the comment next to it. Generated by
`uv run tools/run/envs.py --markdown > docs/environment-variables.md`; do not edit by hand. Each one is also a key of
`orbitals.ini` without the prefix (`runtime/core/base/cfg.c`), except where its row says otherwise.

The runtime reads only `ORBITALS_*`: there is no alias and no fallback for the former names. The "Former name" column
is a historical reference for scripts and profiles written before the rename. `tools/migrate_config.py` rewrites them
once (`--apply`; a dry run by default). Its rule is `MKW_X` to `ORBITALS_X`; the exceptions are listed in
`tools/migrate/mkw-to-orbitals.tsv` (none at present).

| Name | Former name | Read at | What it does |
|---|---|---|---|
"""


def former(name: str, exceptions: dict[str, str]) -> str:
    """The name before the rename: the exception whose new name this is, else the prefix rule backwards."""
    for old, new in exceptions.items():
        if new == name:
            return old
    return "MKW" + name[len("ORBITALS"):]


def exceptions_table() -> dict[str, str]:
    path = ROOT / "tools/migrate/mkw-to-orbitals.tsv"
    out = {}
    for line in path.read_text(encoding="utf-8").splitlines() if path.is_file() else []:
        if line.strip() and not line.startswith("#") and "\t" in line:
            old, new = (x.strip() for x in line.split("\t", 1))
            out[old] = new
    return out


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def main() -> None:
    args = sys.argv[1:]
    if args == ["--markdown"]:
        exc = exceptions_table()
        rows = [f"| `{n}` | `{former(n, exc)}` | `{w}` | {cell(t[:220])} |" for n, (w, t) in sorted(catalogue().items())]
        sys.stdout.write(MARKDOWN_HEAD + "\n".join(rows) + "\n")
        return
    pat = re.compile(args[0]) if args else None
    for name, (where, text) in sorted(catalogue().items()):
        if pat and not pat.search(name):
            continue
        print(f"{name}\t{where}\t{text[:220]}")


if __name__ == "__main__":
    main()
